#!/usr/bin/env node
/**
 * No hand-written copy of a generated type, anywhere a TypeScript or JavaScript tree lives.
 *
 * Owner, 2026-11-19: "There should be no 'hand-written copies of generated types', that is an
 * anti-pattern." A copy drifts silently when the Rust changes; the generated type turns the same
 * drift into a compile error. The sweep that prompted this found copies that had ALREADY drifted
 * and shipped: `UpdateOperationTS` sent 'add' for an enum serde spells "Add" (a cast hid it), a
 * workspace rename sent UpdateWorkspace without the master password the variant requires (so it
 * never deserialized), CreateNode sent `mdx_content`/`is_default` the server has no field for,
 * `GetGroupMessages.before_timestamp` went as a number for a u64, `HeaderObfuscatorSettings`
 * held a u128 key in a number, and `SessionInformation` grew a `full_name` the agent never sends,
 * which the session chip and two tests rendered.
 *
 * The rules (scripts/lib/hand-copy-scan.mjs): a declaration that takes a generated type's name,
 * restates most of its fields, lists its variants, or is an untyped object of its field names,
 * without deriving from it (`Pick`, `Omit`, `Extract`, an intersection, `satisfies`,
 * `everyMember<T>()`). An entry in ALLOW below is a real non-duplicate, each with its reason.
 *
 * Needs the root `npm ci` (for `typescript` and the protocol types package) and the agent
 * submodule; without either it examines nothing, so it fails rather than passing.
 */
import { createRequire } from 'node:module';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { declarationsOf, findHandCopies } from './lib/hand-copy-scan.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ts = createRequire(join(ROOT, 'package.json'))('typescript');

/**
 * Where generated TypeScript lives, and who can see it: protocol types reach every tree; an app
 * SDK's or an app's own bindings only the code of that app. Nothing generated is scanned as a
 * hand copy, and neither is any file carrying ts-rs's "generated" header (the apps vendor the SDK
 * bindings under their own trees).
 */
const APPS_UI = ['citadel-workspaces/src/lib/citadel-apps/', 'citadel-workspaces/src/components/citadel-apps/', 'apps/'];
const CALENDAR = ['citadel-workspaces/src/lib/calendar/', 'citadel-workspaces/src/components/calendar/', 'apps/first-party/calendar/'];
const GENERATED = [
  ['citadel-workspace-types/bindings', null],
  ['citadel-workspace-client-ts/src/types/generated', null],
  ['citadel-internal-service/typescript-client/src/types', null],
  ['citadel-workspace-client-ts/pkg', null],
  ['node_modules/@avarok/citadel-protocol-types/dist', null],
  ['citadel-workspaces/src/lib/citadel-apps/sdk/generated', APPS_UI],
  ['citadel-workspaces/src/lib/citadel-apps/sdk/wire-generated', APPS_UI],
  ['citadel-workspaces/src/lib/calendar/generated', CALENDAR],
  ['apps/first-party/calendar/core/bindings', CALENDAR],
];
const GENERATED_HEADER = /^\/\/ (This file was generated by \[ts-rs\]|Generated by citadel-app-sdk-types )/;

/** Every hand-written TS/JS tree in the repository. */
const HAND = [
  'citadel-workspaces/src', 'citadel-workspaces/integration-tests/src', 'citadel-workspaces/scripts',
  'citadel-workspace-client-ts/src', 'citadel-workspace-client-ts/scripts', 'citadel-workspace-client-ts/examples',
  'citadel-internal-service/typescript-client/src', 'citadel-internal-service/typescript-client/scripts',
  'deploy/tenant-worker', 'scripts', 'apps',
];

const SKIP = /(^|\/)(node_modules|dist|target|pkg)(\/|$)/;
const SOURCE = /\.(ts|tsx|mts|cts|mjs|cjs|js)$/;

/** `path#Name` -> why it is not a copy. */
const ALLOW = new Map(Object.entries({
  // Geometry and UI shapes that share common field names with a generated type by coincidence.
  'citadel-workspaces/src/lib/cdoc/display-list/types.ts#Rect': 'document layout geometry; DrawCommand.fill_rect is a canvas op that happens to share x/y/w/h',
  'citadel-workspaces/src/lib/cdoc/paint/units.ts#PixelRect': 'device-pixel geometry, not a canvas draw op',
  'citadel-workspaces/src/lib/cdoc/paint/page-painter.ts#LinkArea': 'a hit-test rectangle with an href, not a canvas draw op',
  'citadel-workspaces/src/components/documents/__tests__/page-images.test.tsx#Box': 'a test layout box, not a canvas draw op',
  'citadel-workspaces/src/components/documents/ribbon/TablePicker.tsx#Size': 'rows x cols of a table picker; the SDK Size is a pixel width x height',
  'citadel-workspaces/src/components/office/tabs/TabMenu.tsx#MenuItem': 'a React menu entry with an onSelect; the SDK MenuItem is an app toolbar wire item',
  'citadel-workspaces/src/lib/cdoc/paint/canvas-port.ts#Surface': 'a 2D canvas context port; the SDK Surface is the zone an app renders into',
  'citadel-workspaces/src/lib/cdoc/worker/cdoc-host.ts#HostReply': 'the document worker\'s postMessage reply; the SDK HostReply is the guest ABI',
  'citadel-workspaces/src/lib/chat/transport/chat-transport.ts#ChatMessage': 'the UI chat transport\'s message (author object, share, attachment); the SDK ChatMessage is what an app reads',
  'citadel-workspaces/src/lib/citadel-apps/host/__tests__/instance-ihttp-early.test.ts#Transport': 'a test transport double with a port and subscribers, not the SDK Transport enum',
  'citadel-workspaces/src/lib/at-rest/record-crypto.ts#Bytes': 'an alias for Uint8Array in the at-rest crypto port',
  'citadel-workspaces/src/lib/passkey/bytes.ts#Bytes': 'an alias for Uint8Array in the WebAuthn code',
  'citadel-workspaces/src/lib/passkey/browser-authenticator.ts#ClientCapabilities': 'the WebAuthn browser API\'s PublicKeyCredential.getClientCapabilities() result',
  'citadel-workspaces/src/hooks/__tests__/mark-as-read-terminates.test.ts#Group': 'a chat group fixture, not the SDK capability Group',
  'citadel-workspaces/src/lib/calendar/__tests__/booking-rig.ts#Member': 'a calendar booking-rig participant, not the SDK Member',
  'citadel-workspaces/src/lib/calendar/__tests__/tree-rig.ts#Member': 'a calendar tree-rig participant, not the SDK Member',
  'citadel-workspaces/src/lib/calendar/notify-prefs.ts#NoticeKind': 'the calendar\'s own reminder kinds (reminders, invitations, bookings, polls); none is an agent NoticeKind',
  'citadel-workspaces/integration-tests/src/lib/apps.ts#Transport': 'a spec helper\'s request transport, not the SDK Transport enum',
  // UI shapes whose few field names (cid, username, name, success...) a generated type also uses.
  'citadel-workspaces/src/hooks/use-self-name.ts#SelfName': 'this tab\'s own resolved name, each part undefined until loaded; not a peer listing',
  'citadel-workspaces/src/lib/cdoc/chat/chat-app-ports.ts#ChatPeer': 'a chat document\'s resolved other person (name always set) for caret labels; not a peer listing',
  'citadel-workspaces/src/types/group-permissions.ts#GroupRole': 'a browser-kept peer group\'s role (camelCase, GroupPermissions); peer groups have no Rust role type',
  'citadel-workspaces/src/lib/group-conversations/group-file-delivery-state.ts#MemberDeliveryRow': 'one member\'s row of a group file delivery summary, not a signed-out session',
  'citadel-workspaces/src/lib/websocket/session-management.ts#SessionManagementResult': 'the outcome a session-management call returns to the UI, not a group-leave notification',
  'citadel-workspaces/src/lib/calendar/invite-notices.ts#Notice': 'a calendar invitation notice with its told-marker key, before it is posted; not the agent\'s NativeNotice',
  'citadel-workspaces/src/lib/citadel-apps/host/wire-schemas.ts#rect': 'the schema fragment that validates DrawCommand\'s rect fields; it is typed by Schema<DrawCommand>',
}));

function sources(dir) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true, recursive: true })
    .filter((e) => e.isFile() && SOURCE.test(e.name))
    .map((e) => relative(ROOT, join(e.parentPath, e.name)))
    .filter((p) => !SKIP.test(p) && !GENERATED.some(([g]) => p.startsWith(`${g}/`)))
    .filter((p) => !GENERATED_HEADER.test(readFileSync(join(ROOT, p), 'utf8')));
}

const generatedFiles = GENERATED.flatMap(([dir, scope]) => {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs).filter((f) => /\.ts$/.test(f) && !/^index\.(d\.)?ts$/.test(f)).map((f) => ({ file: join(dir, f), scope }));
});
for (const required of ['citadel-workspace-types/bindings', 'citadel-internal-service/typescript-client/src/types', 'node_modules/@avarok/citadel-protocol-types/dist']) {
  if (!generatedFiles.some(({ file }) => file.startsWith(`${required}/`))) {
    console.error(`FAIL: no generated types under ${required}, so this gate examined nothing.\n` +
      'Run `git submodule update --init --recursive` and the root `npm ci` first.');
    process.exit(1);
  }
}

const generated = generatedFiles.flatMap(({ file, scope }) =>
  declarationsOf(ts, file, readFileSync(join(ROOT, file), 'utf8')).map((d) => ({ ...d, scope })));
const handFiles = [...new Set(HAND.flatMap(sources))];
const hand = handFiles.flatMap((f) => declarationsOf(ts, f, readFileSync(join(ROOT, f), 'utf8')));

const stale = [...ALLOW.keys()].filter((key) => !hand.some((h) => `${h.path}#${h.name}` === key));
const findings = findHandCopies(generated, hand, ALLOW);

if (findings.length > 0 || stale.length > 0) {
  console.error('Hand-written copies of generated types:\n');
  for (const f of findings) console.error(`  ${f.path}:${f.line}  ${f.name}  [${f.rule}] ${f.why}`);
  for (const key of stale) console.error(`  ALLOW entry ${key} names no declaration any more; remove it`);
  console.error('\nImport the generated type, or derive the narrower view from it (Pick, Omit, Extract,');
  console.error('`satisfies`, everyMember<T>() for a runtime list). A real non-duplicate goes in ALLOW, with its reason.');
  process.exit(1);
}
console.log(`check-no-hand-copies-of-generated-types: ${hand.length} hand declarations in ${handFiles.length} files, ` +
  `${generated.length} generated; no copies (${ALLOW.size} allowed with reasons).`);
