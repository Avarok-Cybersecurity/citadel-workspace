#!/usr/bin/env node
// Build (or verify) the index of every gate in this repository.
//
// They live across two directories and nothing listed them. The only way to
// learn whether a guard already existed was to read every one of them,
// so four times in one campaign a guard was written that already existed
// elsewhere and better — a listener check, an event guard, a permission gate,
// and a whole test module. Each was found by accident, after the fact.
//
// `--check` fails when the index is out of date, so a new gate cannot be added
// without appearing here. That is the property worth having: an index nobody
// updates is worse than none, because it reads as complete.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const INDEX = 'docs/GATES.md';
const DIRS = ['scripts', 'citadel-workspaces/scripts'];

/** The first sentence of a script's header comment, whichever style it uses. */
function summarise(file) {
  const lines = readFileSync(file, 'utf8').split('\n');
  let i = 0;
  if (lines[i]?.startsWith('#!')) i++;
  const collected = [];
  for (; i < lines.length && collected.length < 6; i++) {
    const line = lines[i].trim();
    if (line === '/**' || line === '') continue;
    const text = line.replace(/^\/\*\*?/, '').replace(/^\*\/?/, '').replace(/^\/\//, '').trim();
    if (!text) { if (collected.length) break; else continue; }
    if (/^(import|const|let|export|function)\b/.test(line)) break;
    collected.push(text);
    if (text.endsWith('.')) break;
  }
  const sentence = collected.join(' ').split(/(?<=\.)\s/)[0] || '(no header summary)';
  return sentence.replace(/\|/g, '\\|').trim();
}

const rows = [];
for (const dir of DIRS) {
  let files = [];
  try {
    files = execSync(`find ${dir} -maxdepth 1 -name 'check-*.mjs'`, { encoding: 'utf8' })
      .trim().split('\n').filter(Boolean).sort();
  } catch { /* directory absent */ }
  for (const file of files) rows.push({ dir, file, name: file.split('/').pop(), summary: summarise(file) });
}

if (!rows.length) {
  console.error('FAIL: found no gate scripts at all — the search has gone stale.');
  console.error('An index that lists nothing reports a completeness it never measured.');
  process.exit(1);
}

const byDir = new Map();
for (const r of rows) {
  if (!byDir.has(r.dir)) byDir.set(r.dir, []);
  byDir.get(r.dir).push(r);
}

let out = `<!-- Generated by scripts/build-gates-index.mjs. Do not edit by hand. -->\n`;
out += `# Every gate in this repository\n\n`;
out += `${rows.length} checks. Regenerate with \`node scripts/build-gates-index.mjs\`;\n`;
out += `\`--check\` fails when this file is stale, so a new gate has to appear here.\n\n`;
out += `**Read this before writing a new guard.** Four times in one campaign a check\n`;
out += `was written that already existed elsewhere and better, because nothing listed\n`;
out += `what was already here.\n`;
for (const [dir, list] of byDir) {
  out += `\n## \`${dir}/\`\n\n| gate | what it fails on |\n|---|---|\n`;
  for (const r of list) out += `| \`${r.name}\` | ${r.summary} |\n`;
}

const wantCheck = process.argv.includes('--check');
const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
if (wantCheck) {
  if (current !== out) {
    console.error(`::error file=${INDEX}::${INDEX} is out of date`);
    console.error(`\nFAIL: the gate index does not match the gates on disk.`);
    console.error(`Run: node scripts/build-gates-index.mjs`);
    process.exit(1);
  }
  console.log(`OK: the gate index lists all ${rows.length} gate(s).`);
} else {
  writeFileSync(INDEX, out);
  console.log(`Wrote ${INDEX} with ${rows.length} gate(s).`);
}
