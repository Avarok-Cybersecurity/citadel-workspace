#!/usr/bin/env node
// Build (or verify) the index of every gate in this repository.
//
// They live across two directories and nothing listed them. The only way to
// learn whether a guard already existed was to read every one of them,
// so four times in one campaign a guard was written that already existed
// elsewhere and better — a listener check, an event guard, a permission gate,
// and a whole test module. Each was found by accident, after the fact.
//
// `--check` fails when the index is out of date, so a new gate cannot be added
// without appearing here. That is the property worth having: an index nobody
// updates is worse than none, because it reads as complete.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const INDEX = 'docs/GATES.md';
const DIRS = ['scripts', 'citadel-workspaces/scripts'];

/** The first sentence of a script's header comment, whichever style it uses. */
function summarise(file) {
  const lines = readFileSync(file, 'utf8').split('\n');
  let i = 0;
  if (lines[i]?.startsWith('#!')) i++;
  const collected = [];
  for (; i < lines.length && collected.length < 6; i++) {
    const line = lines[i].trim();
    if (line === '/**' || line === '') continue;
    const text = line.replace(/^\/\*\*?/, '').replace(/^\*\/?/, '').replace(/^\/\//, '').trim();
    if (!text) { if (collected.length) break; else continue; }
    if (/^(import|const|let|export|function)\b/.test(line)) break;
    collected.push(text);
    if (text.endsWith('.')) break;
  }
  const sentence = collected.join(' ').split(/(?<=\.)\s/)[0] || '(no header summary)';
  return sentence.replace(/\|/g, '\\|').trim();
}

const rows = [];
for (const dir of DIRS) {
  let files = [];
  try {
    files = execSync(`find ${dir} -maxdepth 1 -name 'check-*.mjs'`, { encoding: 'utf8' })
      .trim().split('\n').filter(Boolean).sort();
  } catch {
    // A missing scan root is a FAILURE, not an empty result.
    //
    // `citadel-workspaces/scripts` lived in a submodule until the UI was folded
    // in. In a worktree without submodules the find failed, this swallowed it, and the generator wrote a
    // 57-gate index -- while a full checkout has 98. `--check` then PASSED on
    // the truncated index and CI, which does check out submodules, failed with
    // "out of date" and no indication of why. The anti-vacuity floor below
    // could not catch it either: it only fires when NO gates are found, and 57
    // is not none.
    console.error(`FAIL: scan root '${dir}' does not exist.`);
    console.error('An index built from a subset of its roots reports a');
    console.error('completeness it never measured.');
    process.exit(1);
  }
  for (const file of files) rows.push({ dir, file, name: file.split('/').pop(), summary: summarise(file) });
}

if (!rows.length) {
  console.error('FAIL: found no gate scripts at all — the search has gone stale.');
  console.error('An index that lists nothing reports a completeness it never measured.');
  process.exit(1);
}

const byDir = new Map();
for (const r of rows) {
  if (!byDir.has(r.dir)) byDir.set(r.dir, []);
  byDir.get(r.dir).push(r);
}

let out = `<!-- Generated by scripts/build-gates-index.mjs. Do not edit by hand. -->\n`;
out += `# Every gate in this repository\n\n`;
out += `${rows.length} checks. Regenerate with \`node scripts/build-gates-index.mjs\`;\n`;
out += `\`--check\` fails when this file is stale, so a new gate has to appear here.\n\n`;
out += `**Read this before writing a new guard.** Four times in one campaign a check\n`;
out += `was written that already existed elsewhere and better, because nothing listed\n`;
out += `what was already here.\n`;
out += `
## Running them before CI does

\`node scripts/preflight.mjs\` runs every gate here that needs no Docker, in the directory and
with the environment CI gives it. Its list is DERIVED from \`validate.yml\`
(\`scripts/lib/preflight-plan.mjs\`, which is also the one place that lists what it skips, and
why). It fails first if this clone has no hooks installed, or if \`node\` is
not the major CI's gate jobs pin (derived from their \`actions/setup-node\` steps; where CI pins
two majors, the one covering more gates wins and the rest are printed).

The hooks run tiers of it, installed by the root \`prepare\` script (\`npm install\`):

| hook | runs |
|---|---|
| pre-commit, pre-merge-commit | static gates whose source reads the staged paths, eslint on staged files, \`cargo fmt\` for touched crates. Not the gates that drive a browser or a built bundle: pre-push and CI run those |
| pre-push | by what the pushed commits change: UI -> typecheck, eslint, vitest, the browser gates, UI gates; Rust -> fmt, clippy, tests of that workspace; scripts/workflows -> every parent gate. Always: submodule work committed, pointers pushed |

**Pushing.** Inside \`git push\` the pre-push hook only VERIFIES: git holds the connection to the
remote open for the whole hook, and GitHub drops it during a long one. Run the tier first, with no
push in flight, then push; the hook passes in seconds, or fails at once naming what has not passed:

    node scripts/pre-push-tier.mjs --remote origin   # runs the pre-push hook itself, via git hook run
    git push

Every check passed is stamped over its exact inputs (every file, the installs, the toolchain, the
environment; \`scripts/lib/preflight-stamp.mjs\`), so a retried push or a second tier run over the
same tree is instant, and any changed input runs that check again. Variables are inputs: run the
tier and the push with the same \`CARGO_*\`, \`RUSTFLAGS\`, \`NODE_OPTIONS\`. Heavy runs on one machine
queue on one lock (\`~/.cache/citadel-preflight/hook.lock\`, times in \`hook-times.tsv\` beside it),
first come first served: a later arrival never takes it ahead of a waiter.

The only bypass is git's own, \`--no-verify\`, for one commit or push.

\`node scripts/merge-preview.mjs --repo parent|agent\` merges every open PR into master
in a scratch clone, names each one that conflicts (a PR that conflicts with its base gets no CI
run at all), and runs the static gates and TypeScript build on the combination; \`agent\` merges
the agent repo's open PRs and moves its pointer inside the parent's master.

\`CI_PARITY=1\` on a geometry or harness run (\`npm run check:ui-sweep\`, \`check:chat-polish\`,
\`check:mobile\`) makes Chromium report CI's runner (4 cores, deviceMemory 8) so Animations=Auto resolves as
on CI, throttles the CPU 4x, and asserts the Node major. It reproduces neither the Docker stack
nor Linux or Windows rendering; scenarios that pin a motion tier keep it.

A sidebar motion sample in which nothing was painted for 50 ms or more is not evidence about the motion,
and is not judged by it (\`citadel-workspaces/scripts/lib/polish-harness/stall-attribution.mjs\`). This is the
re-measurement of an invalid sample, not a retry of a failed assertion. The same transition is measured again
from fresh tabs until 5 clean samples exist (8 attempts at most), and the stalled sample is attributed against
them. Main-thread, renderer and GPU-process CPU are each allowed max(2 measured ticks, min(2 sd, gap/4)) over
their clean mean. Any counter above that blames the page: red, named, never re-measured. None above blames the
runner: the sample is discarded and printed, pass or fail, and the verdict needs every clean sample to pass the
unchanged rules. Too few clean samples within the cap is red, and so are discards above 10% of the sweep's
attributable transitions. Each counter's tick is measured at the start of the run. A counter coarser than
20 ms, or one that does not advance, is left out; without the main thread or the renderer, nothing is
discarded. WebKit and every CPU-throttled run (CDP counts throttling as CPU time) never discard: a long frame
there is judged as sampled and named.
`;
for (const [dir, list] of byDir) {
  out += `\n## \`${dir}/\`\n\n| gate | what it fails on |\n|---|---|\n`;
  for (const r of list) out += `| \`${r.name}\` | ${r.summary} |\n`;
}

const wantCheck = process.argv.includes('--check');
const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
if (wantCheck) {
  if (current !== out) {
    console.error(`::error file=${INDEX}::${INDEX} is out of date`);
    console.error(`\nFAIL: the gate index does not match the gates on disk.`);
    console.error(`Run: node scripts/build-gates-index.mjs`);
    process.exit(1);
  }
  console.log(`OK: the gate index lists all ${rows.length} gate(s).`);
} else {
  writeFileSync(INDEX, out);
  console.log(`Wrote ${INDEX} with ${rows.length} gate(s).`);
}
