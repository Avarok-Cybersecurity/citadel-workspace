/**
 * Turn wasm-bindgen's `--target web` glue into a factory, so each Durable Object instantiates the
 * module into a wasm instance of its own.
 *
 *   node make-instance-factory.mjs <glue.js> <out.mjs>
 *
 * The glue holds the instance in module-level variables, and an ES module is evaluated once per
 * isolate — while several Durable Objects can share an isolate. With the glue as it is, those
 * objects share one linear memory: every Rust global, the async executor's task queue and the
 * logger. Wrapping the whole glue in a function gives every call its own copy of those variables,
 * hence its own `WebAssembly.Instance`. The glue has no imports; its only exports are the classes
 * and functions `#[wasm_bindgen]` exposes, `initSync` and the default async init, which this
 * rewrites and checks for, so a wasm-bindgen upgrade that changes that shape fails the build
 * instead of producing a shared instance again.
 */
import { readFileSync, writeFileSync } from "node:fs";

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error("usage: node make-instance-factory.mjs <glue.js> <out.mjs>");
  process.exit(2);
}
const glue = readFileSync(input, "utf8");

function fail(why) {
  console.error(`make-instance-factory: ${input}: ${why}`);
  process.exit(1);
}

if (/^import\s/m.test(glue)) fail("the glue imports modules; they cannot move inside a function");
const tail = "export { initSync, __wbg_init as default };";
if (!glue.trimEnd().endsWith(tail)) fail(`expected the glue to end with \`${tail}\``);

const names = [...glue.matchAll(/^export (?:class|function) (\w+)\b/gm)].map((m) => m[1]);
if (names.length === 0) fail("no exported classes or functions found");
let body = glue
  .trimEnd()
  .slice(0, -tail.length)
  .replace(/^export (class|function) /gm, "$1 ");
const leftover = body.match(/^export\b.*$/m);
if (leftover) fail(`unexpected export: ${leftover[0]}`);

const factory = `// GENERATED by make-instance-factory.mjs from ${input.split("/").pop()}; do not edit.
export function instantiate(module) {
${body}
  initSync({ module });
  return { ${names.join(", ")}, memory: () => wasm.memory };
}
`;
writeFileSync(output, factory);
console.log(`make-instance-factory: ${output} (exports: ${names.join(", ")})`);
