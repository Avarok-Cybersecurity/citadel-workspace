//! The shared runtime-wire fixture (`apps/runtime-fixtures/apps-runtime-wire.json`) is exactly
//! what the kernel's codecs produce today. The page's tests read the same file with the page's
//! codecs (`citadel-workspaces/.../runtime/__tests__/runtime-wire-fixture.test.ts`), so the two
//! sides are held to one set of bytes, not to two copies of an assumption.
//!
//! When a shape changes on purpose, regenerate with `CITADEL_WRITE_RUNTIME_WIRE_FIXTURE=1` and
//! review the diff: every changed line is a change the page must make too.

use super::runtime_wire_calls::{host_calls, host_replies, request_refusals, routes};
use super::runtime_wire_frames::{from_wire, to_wire};
use super::runtime_wire_relay::{addressing, relay};
use serde_json::json;
use std::path::PathBuf;

fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../apps/runtime-fixtures/apps-runtime-wire.json")
}

fn expected() -> String {
    let document = json!({
        "about": "Generated by citadel-workspace-server-kernel runtime_wire_fixture_tests; read by the UI's runtime-wire-fixture.test.ts. Hex is CBOR.",
        "host_calls": host_calls(),
        "host_replies": host_replies(),
        "request_refusals": request_refusals(),
        "routes": routes(),
        "frames_to_wire": to_wire(),
        "frames_from_wire": from_wire(),
        "relay": relay(),
        "addressing": addressing(),
    });
    let mut text = serde_json::to_string_pretty(&document).expect("json");
    text.push('\n');
    text
}

#[test]
fn the_shared_runtime_wire_fixture_is_what_the_kernel_encodes() {
    let path = fixture_path();
    let want = expected();
    if std::env::var_os("CITADEL_WRITE_RUNTIME_WIRE_FIXTURE").is_some() {
        std::fs::write(&path, &want).expect("write the runtime-wire fixture");
    }
    let have = std::fs::read_to_string(&path).expect("read the runtime-wire fixture");
    assert!(
        have == want,
        "{} is not what the kernel encodes; regenerate it (see this file's header) and make \
         the page agree with the diff",
        path.display()
    );
}
