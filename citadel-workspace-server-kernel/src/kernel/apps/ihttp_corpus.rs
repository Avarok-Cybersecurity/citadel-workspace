//! The shared internal-HTTP frame corpus (`apps/catalogue/fixtures/ihttp-frame-cases.json`):
//! bytes, and what every reader must make of them. Written here, read back by the wire
//! crate's decoder and the kernel's relay (ihttp_corpus_tests.rs) and by the page's reader
//! (`citadel-workspaces/.../host/__tests__/ihttp-frame-corpus.test.ts`).
//!
//! `expect` is written by hand beside each case, never computed from a decoder: `End`,
//! `Cancel(Timeout)`, ..., or `refused:<FrameError variant>`. `layer` says who must refuse:
//! `shape` (not a frame of a known kind with its fields and types: every reader refuses it)
//! or `rules` (a well-shaped frame that breaks a limit, a version or a path rule, or carries a
//! field the wire denies: the agent and the kernel refuse it, and the page, which reads only
//! frames one of them has already validated and re-encoded, is not asked).

use citadel_ihttp_types::{CancelReason, IhttpFrame, IhttpFrameKind, IhttpMethod};
use serde::Serialize;
use serde_json::{json, Value};

pub(crate) const CORPUS: &str = "../apps/catalogue/fixtures/ihttp-frame-cases.json";

/// Every reason, each a case: a reader that cannot name one refuses a frame it should read.
pub(super) const REASONS: [CancelReason; 11] = [
    CancelReason::Caller,
    CancelReason::Timeout,
    CancelReason::TooLarge,
    CancelReason::Busy,
    CancelReason::RateLimited,
    CancelReason::NoRoute,
    CancelReason::Refused,
    CancelReason::Failed,
    CancelReason::Closed,
    CancelReason::Protocol,
    CancelReason::Unavailable,
];

pub(super) fn raw<T: Serialize>(value: &T) -> Vec<u8> {
    let mut out = Vec::new();
    ciborium::ser::into_writer(value, &mut out).expect("serialisable");
    out
}

pub(super) fn frame(kind: IhttpFrameKind) -> IhttpFrame {
    IhttpFrame {
        v: 1,
        stream: 1,
        kind,
    }
}

/// A head the kernel's test install serves (test_runtime: `GET /cards` in `workspace`).
pub(crate) fn served_head() -> IhttpFrameKind {
    IhttpFrameKind::RequestHead {
        method: IhttpMethod::Get,
        path: "/cards".into(),
        query: None,
        headers: vec![],
        body_len: Some(0),
        app_id: "com.acme.kanban".into(),
        scope_key: "workspace".into(),
    }
}

pub(super) fn head_with(change: impl FnOnce(&mut IhttpFrameKind)) -> IhttpFrame {
    let mut kind = served_head();
    change(&mut kind);
    frame(kind)
}

pub(super) fn set_path(kind: &mut IhttpFrameKind, to: &str) {
    if let IhttpFrameKind::RequestHead { path, .. } = kind {
        *path = to.into();
    }
}

pub(super) struct Case {
    name: String,
    bytes: Vec<u8>,
    expect: String,
    layer: &'static str,
}

pub(super) fn case(name: &str, bytes: Vec<u8>, expect: &str, layer: &'static str) -> Case {
    Case {
        name: name.into(),
        bytes,
        expect: expect.into(),
        layer,
    }
}

/// The corpus file's whole text, as this module writes it.
pub(crate) fn document() -> String {
    let cases: Vec<Value> = super::ihttp_corpus_cases::cases()
        .into_iter()
        .map(|c| json!({ "name": c.name, "hex": hex::encode(c.bytes), "expect": c.expect, "layer": c.layer }))
        .collect();
    let document = json!({
        "_about": "Generated by citadel-workspace-server-kernel kernel::apps::ihttp_corpus (CITADEL_WRITE_IHTTP_CORPUS=1); `expect` is hand-written there. Read by the wire crate's decoder and the kernel relay (ihttp_corpus_tests.rs) and the page (host/__tests__/ihttp-frame-corpus.test.ts). layer: shape = every reader refuses; rules = the agent and kernel refuse, the page reads only frames they validated.",
        "cases": cases,
    });
    let mut text = serde_json::to_string_pretty(&document).expect("json");
    text.push('\n');
    text
}
